-- 자료 조회수 (#244, #245, spec 3-2 §3-2-2).
--
-- 상세를 연 횟수를 센다. 중복은 걸러내지 않으므로 조회 기록 테이블은 두지 않는다
-- (2-1 §2-1-1) — 걸러내려면 (회원, 자료) 쌍을 남겨야 하고 회원 삭제 두 경로에
-- CASCADE가 붙는다.
--
-- NOT NULL DEFAULT 0이라 이미 쌓인 자료도 이 문장 하나로 0을 갖는다. 따로 채우는
-- UPDATE가 필요 없다.
--
-- 인덱스를 걸지 않는다. 상세를 열 때마다 갱신되는 컬럼이라 인덱스를 달면 조회 경로가
-- 인덱스까지 함께 고쳐야 한다 — 자료 수백 건 규모에서 정렬 비용보다 그쪽이 크다.
ALTER TABLE notes
    ADD COLUMN view_count bigint NOT NULL DEFAULT 0;
