import type * as React from 'react'
import { cn } from '@/lib/utils'

/**
 * 목록 표를 감싸는 자리.
 *
 * **카드가 아니다** (#268). 한때 `Card`로 감쌌는데 그 컴포넌트가 `bg-card`·`border`·
 * `shadow-sm`을 붙여, 무채색 팔레트에서 **본문 배경과 미묘하게 다른 회색 판이 그림자를
 * 달고 얹혔다.**
 *
 * 목록은 **읽는 것이지 집어 드는 것이 아니다.** 카드는 "이것이 하나의 덩어리"라고 말하는
 * 장치인데 표는 이미 행과 열로 스스로 경계를 만든다 — 그 위에 판을 깔면 **경계가 두 겹**이
 * 된다. 배경을 걷고 **위아래 선만** 남기면 표가 배경 위에 놓인 것처럼 읽힌다.
 *
 * 모서리는 각진 채로 둔다 (#218) — 행이 직선으로 쌓이는데 래퍼만 둥글면 네 모서리에서
 * 행이 잘려 보인다. 지금은 배경이 없어 잘릴 것도 없지만, **둥글게 만들 이유도 없다.**
 *
 * **네 목록이 이 하나를 같이 쓴다** — 공지·자료게시판·자유게시판·회원 관리. 각자 클래스를
 * 들고 있으면 한 곳만 고쳐지고, 그 어긋남은 화면을 나란히 놓고 봐야 드러난다.
 */
export function ListSurface({
  className,
  ...props
}: React.ComponentProps<'div'>) {
  return (
    <div
      className={cn(
        'overflow-hidden border-y border-border',
        /*
         * **행 사이는 위아래 선보다 연하다.** 셋이 같은 굵기·같은 색이면 표가 다시
         * 격자처럼 읽힌다 — 바깥 선이 "여기까지가 목록"을 말하고 안쪽 선은 행을 가르기만
         * 하면 된다. 그 위계를 투명도로 준다.
         *
         * 행을 그리는 방식이 화면마다 다르다 — 공지·자유게시판은 `<li>`, 자료·회원 관리는
         * `<tr>`(shadcn `Table`)다. **둘 다 여기서 덮는다**: `ui/table.tsx`를 고치면
         * 목록이 아닌 표까지 따라 바뀌고, 각 화면에서 덮으면 네 곳이 갈린다.
         */
        '[&_li]:border-border/60 [&_tr]:border-border/60',
        className,
      )}
      {...props}
    />
  )
}
