export interface Stat {
  /**
   * 카운트업 대상 숫자.
   *
   * 숫자와 단위를 나눠 둔 이유는 화면에서 문자열을 파싱하지 않기 위해서다.
   * `'39년'`을 쪼개는 코드는 `'3년차'` 같은 값이 들어오는 순간 틀린다.
   */
  value: number
  /** 숫자 뒤에 붙는 단위. 애니메이션 대상이 아니라 고정이다. */
  unit: string
  /**
   * 최소 표시 자릿수. 모자란 자리는 앞을 0으로 채운다.
   * 아직 실제 값이 없는 칸을 `00명`처럼 보이게 해 자리표시자임을 드러내는 용도다.
   */
  minDigits?: number
  label: string
}

