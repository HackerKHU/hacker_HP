/**
 * 개인정보처리방침.
 *
 * **DB 스키마는 이 문서와 일치한다** (#80). **수집 항목은 `users` 표와 행 단위로 대조한다.**
 * 저장하는 것을 여기 적지 않으면 이 문서가 거짓이 된다 — `/privacy`는 비로그인에게도 열리는
 * 공개 라우트다. 스키마에 컬럼을 더하는 PR은 여기도 같이 본다.
 *
 * 빠져 있는 컬럼과 이유 — `id`와 `version`은 개인정보가 아니다. `role`·`status`는 서비스가
 * 부여하는 이용 상태이고 본인이 화면에서 늘 보는 값이라 수집 항목으로 따로 고지하지 않는다.
 *
 * **문체 두 가지.**
 *
 * 첫째, 줄글로 이어 쓴다. 조항을 잘게 끊으면 읽는 사람이 자기와 상관있는 대목을 찾지
 * 못한다. `items`는 나열이 곧 내용인 곳(수집 항목·위탁 업체)에만 쓴다.
 *
 * 둘째, **본문에 줄표(—)를 쓰지 않는다.** 줄표는 "덧붙이자면"에 가까운 부호라 뒤에 오는
 * 말이 곁가지처럼 읽힌다. 그런데 이 문서에서 줄표 뒤에 있던 것은 대개 곁가지가 아니라
 * 조건이었다. 거부된 뒤 같은 계정으로 다시 신청할 수 있다는 것, 남는 것이 이름 자리뿐이라는 것 같은
 * 대목이다. 문장을 끊어 각각을 제 문장으로 세운다. 이 규칙은 본문에만 걸린다. 주석은
 * 저장소의 다른 코드와 결을 맞춘다.
 *
 * 근거 문서 — 수집 항목은 `spec/3-2-DESIGN-CONTRACT.md`의 `users` 테이블, 가입 거부 시
 * 신청 정보 초기화와 회원 제거 시 삭제는 `spec/3-1-DESIGN-ARCHITECTURE.md` §3-1-2, 회원 제거 후 콘텐츠를 남기는
 * 것은 `spec/2-2-OPERATOR-REQUIREMENTS.md` §2-2-4, 위탁 업체는 `docs/ops/infra.md`와
 * `spec/3-3-DESIGN-DECISIONS.md`.
 *
 * **탈퇴 후에도 남는 것은 반드시 여기 적는다** (#49). 계정만 지운다는 설명으로 대신할 수
 * 없다 — 올린 파일 자체에 개인정보가 들어 있을 수 있고, 이용자는 자기가 올린 것이 남는지
 * 알 수 없다.
 *
 * **분석 도구는 아직 붙어 있지 않다.** Amplitude를 연동하면 그 수집 항목을 여기 더한다
 * (#87). 붙지도 않은 것을 미리 적지 않는다 — 안 하는 수집을 적는 것도 거짓이다.
 */

